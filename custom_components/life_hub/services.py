_current_hass: HomeAssistant | None = None


def _get_provider_client(hass: HomeAssistant, provider_type: str):
    """Get client for a specific provider type via O(1) lookup."""
    client_map = hass.data.get(DOMAIN, {}).get("client_map", {})
    for key, (client, rt) in client_map.items():
        if key.startswith(f"{provider_type}:"):
            return client, rt
    # Fallback: iterate entries (safe for edge cases)
    for entry in hass.config_entries.async_entries(DOMAIN):
        runtime = getattr(entry, "runtime_data", None)
        if runtime is None:
            continue
        for key, rt in runtime.providers.items():
            if key.startswith(f"{provider_type}:") and hasattr(rt, "client"):
                return rt.client, rt
    raise HomeAssistantError(f"未找到 {provider_type} 集成")


def _make_handler(provider: str, method: str):
    """Factory: create a handler that calls ``client.{method}(**call.data)``."""
    async def handler(call: ServiceCall) -> Any:
        client, _ = _get_provider_client(_current_hass, provider)
        try:
            result = await getattr(client, method)(**dict(call.data))
            return result or {}
        except TypeError as err:
            _LOGGER.warning("_make_handler %s.%s failed: %s", provider, method, err)
            raise HomeAssistantError(f"Provider {provider} method {method} failed: {err}") from err
    return handler


def _make_dispatch_handler(provider: str):
    """Factory: create a handler that dispatches ``client.{method}(**params)``.

    Expected service call data: ``{"method": "...", "params": {...}}``.
    """
    async def handler(call: ServiceCall) -> Any:
        client, _ = _get_provider_client(_current_hass, provider)
        method = call.data["method"]
        params = call.data.get("params", {})
        try:
            fn = getattr(client, method)
            result = await fn(**params)
            return result or {}
        except TypeError as err:
            _LOGGER.warning("_make_dispatch_handler %s.%s failed: %s", provider, method, err)
            raise HomeAssistantError(f"Provider {provider} method {method} failed: {err}") from err
    return handler


