"""Life Hub services — all providers.

Strategy:
- Generic handlers (simply call client.{method} with ServiceCall.data as kwargs)
  are generated by ``_make_handler()`` to eliminate fliggy/baidu/tongcheng boilerplate.
- Providers with special dispatch logic (yiming, meituan) or result-wrapping (gaode)
  keep hand-written closures.
- Registration is a single declarative list at the bottom, not 350 lines.
"""

from __future__ import annotations

import json
import logging
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any

import voluptuous as vol
from homeassistant.core import HomeAssistant, ServiceCall, SupportsResponse
from homeassistant.exceptions import HomeAssistantError

_LOGGER = logging.getLogger(__name__)

from .const import DOMAIN


# ═══════════════════════════════════════════════════════════
# Infrastructure
