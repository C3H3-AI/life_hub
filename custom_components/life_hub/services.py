async def _handle_yiming(call: ServiceCall) -> Any:
    """Dispatch yiming API calls via method+params."""
    method = call.data["method"]

    # Special: claim_all iterates over all yiming accounts
    if method == "claim_all":
        results = {}
        client_map = _current_hass.data.get(DOMAIN, {}).get("client_map", {})
        for key, (client, rt) in client_map.items():
            if not key.startswith("yiming:"):
                continue
            try:
                result = await client.receive_all_coupons()
                results[key] = {"status": "ok", "result": result.get("msg", "ok")}
            except Exception as err:
                results[key] = {"status": "error", "error": str(err)}
        return results

    client, _ = _get_provider_client(_current_hass, "yiming")
    params = call.data.get("params", {})

    def _lat():
        return _get_lng_lat(_current_hass)

    _DISPATCH = {
        # 查询类
        "get_balance": lambda: client.get_balance(),
        "get_member_info": lambda: client.get_member_info(),
        "get_coupon_sum": lambda: client.get_coupon_sum(),
        "get_integral": lambda: client.get_integral(),
        "get_user_info": lambda: client.get_user_info(),
        "get_app_notice": lambda: client.get_app_notice(),
        "get_coupon_pools": lambda: client.get_coupon_pools(),
        "get_orders": lambda: client.get_orders(params.get("page_num", 1), params.get("page_size", 5)),
        "get_my_coupons": lambda: client.get_my_coupons(params.get("page_num", 1), params.get("page_size", 20), params.get("usable", 1)),
        "get_integral_detail": lambda: client.get_integral_detail(params.get("page_num", 1), params.get("page_size", 5)),
        "get_recharge_list": lambda: client.get_recharge_list(),
        "get_app_equity": lambda: client.get_app_equity(),
        "get_user_info_v2": lambda: client.get_user_info_v2(),
        "get_qrcode": lambda: client.get_qrcode(),
        "get_order": lambda: client.get_order(params["order_no"]),
        "get_transaction_details": lambda: client.get_transaction_details(),
        "get_default_address": lambda: client.get_default_address(),
        # 门店/位置
        "get_nearest_store": lambda: client.query_nearest_enable_store(*_lat()),
        "get_menu": lambda: client.get_goods_category(params.get("shop_code", ""), *_lat()),
        "get_sku_info": lambda: client.get_sku_info(params["goods_id"], params["shop_code"]),
        "search_stores": lambda: client.query_store_list_by_page(*_lat(), params.get("city", ""), params.get("keyword", "")),
        "get_delivery_time": lambda: client.get_delivery_time(params["store_code"], params.get("order_type", "3")),
        "get_nearby_addresses": lambda: client.get_personal_nearly_address_list(*_lat()),
        "get_store_info": lambda: client.get_store_info(params["store_code"]),
        "get_region_list": lambda: client.get_region_list(params.get("user_city", "")),
        "get_current_city": lambda: client.get_current_city(*_lat()),
        "query_nearly_store": lambda: client.query_nearly_store(*_lat(), params.get("city", "")),
        "query_nearly_store_by_distance": lambda: client.query_nearly_store_by_distance(*_lat(), params.get("distance", 3000)),
        "get_nearly_store_one_km": lambda: client.get_nearly_store_one_km(*_lat()),
        # 下单/购物车
        "calculate_cart": lambda: client.shopping_cart_calculation(_parse_json_list(params.get("goods_list", "[]"))),
        "pre_create_order": lambda: client.pre_create_order(params.get("shop_code", ""), _parse_json_list(params.get("goods_list", "[]"))),
        "submit_order": lambda: client.submit_order(
            shop_code=params.get("shop_code", ""),
            shop_name=params.get("shop_name", ""),
            goods_list=_parse_json_list(params.get("goods_list", "[]")),
            order_type=params.get("order_type", "1"),
            pay_type=params.get("pay_type", 1),
            mobile=params.get("mobile", ""),
            remark=params.get("remark", ""),
            longitude=params.get("longitude"), latitude=params.get("latitude"),
        ),
        # 优惠券
        "receive_all_coupons": lambda: client.receive_all_coupons(),
        "receive_coupon": lambda: client.receive_coupon(params["equity_pool_id"], params["coupon_code"], params.get("receive_num", 1)),
        # 收藏
        "collect_store_query": lambda: client.collect_store_query(*_lat(), params.get("city", "")),
        "collect_store_create": lambda: client.collect_store_create(params["store_id"]),
    }
    fn = _DISPATCH.get(method)
    if fn is None:
        raise HomeAssistantError(f"未知的一鸣 API 方法: {method}")
    return await fn()


async def _handle_meituan(call: ServiceCall) -> dict:
    """Dispatch meituan API calls via method+params."""
    client, _ = _get_provider_client(_current_hass, "meituan")
    return await client.call_method(call.data["method"], call.data.get("params", {})) or {}


async def _handle_mcdonalds(call: ServiceCall) -> dict:
    """McDonald's MCP call_tool with JSON string support."""
    client, _ = _get_provider_client(_current_hass, "mcdonalds")
    args_raw = call.data.get("arguments", "{}")
    args = json.loads(args_raw) if isinstance(args_raw, str) else args_raw
    return await client.call_tool(call.data["tool_name"], args) or {}


